import * as fs from "node:fs/promises";
import * as path from "node:path";
import { containsVersionSentinel, versionSentinelFor } from "../native/version-sentinel.js";

const outputPath = path.join(import.meta.dir, "../native/embedded-addon.js");
const packageJsonPath = path.join(import.meta.dir, "../package.json");
const nativeDir = path.join(import.meta.dir, "../native");
const archivePrefix = "embedded-addons.";
const archiveSuffix = ".tar.gz";

/** Byte offset of the ustar header's 12-byte mtime field. */
const TAR_MTIME_OFFSET = 136;
/** Length of every ustar header block, and of the numeric mtime field inside it. */
const TAR_BLOCK_BYTES = 512;
const TAR_MTIME_LENGTH = 12;
/** Byte offset and length of the ustar header's size field. */
const TAR_SIZE_OFFSET = 124;
const TAR_SIZE_LENGTH = 12;
/** Byte offset, length, and blanked representation of the ustar header checksum field. */
const TAR_CHECKSUM_OFFSET = 148;
const TAR_CHECKSUM_LENGTH = 8;
const TAR_BLANK = 0x20;
const TAR_ZERO = 0x30;

/** Octal numeric field of a ustar header block, as a number. */
function readTarOctal(block: Uint8Array, offset: number, length: number, label: string): number {
	const raw = Buffer.from(block.subarray(offset, offset + length)).toString("ascii");
	const text = raw.slice(0, raw.indexOf("\0") === -1 ? raw.length : raw.indexOf("\0")).trim();
	if (text === "") return 0;
	if (!/^[0-7]+$/.test(text)) throw new Error(`Embedded addon archive has a non-octal ${label} field: ${raw}`);
	return Number.parseInt(text, 8);
}

/**
 * Build the addon archive with fixed entry timestamps.
 *
 * `Bun.Archive` stamps every entry with the time the archive was written — and
 * checksums the header that carries it — so two embeddings of unchanged addons
 * produced different `tar.gz` bytes and, because the archive is embedded
 * verbatim, different binaries. The tar layout is still `Bun.Archive`'s; each
 * header's mtime is normalized to `0` and its checksum recomputed, which is
 * what a reproducible archive is. Nothing else reads those fields: the runtime
 * extractor takes entry names, sizes and payloads only
 * (`native/loader-state.js`), and the version sentinel decides staleness.
 */
async function buildAddonArchive(entries: Record<string, Uint8Array>): Promise<Uint8Array> {
	const tar = new Uint8Array(await new Bun.Archive(entries).bytes());
	for (let offset = 0; offset + TAR_BLOCK_BYTES <= tar.length;) {
		const header = tar.subarray(offset, offset + TAR_BLOCK_BYTES);
		// Two zero blocks terminate the archive; the first byte being 0 is enough
		// to stop, exactly as the extractor decides it.
		if (header[0] === 0) break;
		const size = readTarOctal(header, TAR_SIZE_OFFSET, TAR_SIZE_LENGTH, "size");
		header.fill(TAR_ZERO, TAR_MTIME_OFFSET, TAR_MTIME_OFFSET + TAR_MTIME_LENGTH - 1);
		header[TAR_MTIME_OFFSET + TAR_MTIME_LENGTH - 1] = 0;
		header.fill(TAR_BLANK, TAR_CHECKSUM_OFFSET, TAR_CHECKSUM_OFFSET + TAR_CHECKSUM_LENGTH);
		let checksum = 0;
		for (const byte of header) checksum += byte;
		const digits = checksum.toString(8).padStart(TAR_CHECKSUM_LENGTH - 2, "0");
		for (let index = 0; index < digits.length; index += 1) {
			header[TAR_CHECKSUM_OFFSET + index] = digits.charCodeAt(index);
		}
		header[TAR_CHECKSUM_OFFSET + TAR_CHECKSUM_LENGTH - 2] = 0;
		header[TAR_CHECKSUM_OFFSET + TAR_CHECKSUM_LENGTH - 1] = TAR_BLANK;
		offset += TAR_BLOCK_BYTES + Math.ceil(size / TAR_BLOCK_BYTES) * TAR_BLOCK_BYTES;
	}
	return new Uint8Array(Bun.gzipSync(tar, { level: 9 }));
}

const embeddedAddonTypedefs = `/** @typedef {"modern" | "baseline" | "default"} EmbeddedAddonVariant */

/**
 * @typedef {Object} EmbeddedAddonFile
 * @property {EmbeddedAddonVariant} variant
 * @property {string} filename
 * @property {number} size
 * @property {string=} filePath
 */

/**
 * @typedef {Object} EmbeddedAddonArchive
 * @property {"tar.gz"} format
 * @property {string} filename
 * @property {string} filePath
 */

/**
 * @typedef {Object} EmbeddedAddon
 * @property {string} platformTag
 * @property {string} version
 * @property {EmbeddedAddonFile[]} files
 * @property {EmbeddedAddonArchive=} archive
 */`;

const stubContent = `
// AUTOGENERATED FILE -- DO NOT EDIT DIRECTLY
// See scripts/embed-native.ts

${embeddedAddonTypedefs}

/** @type {EmbeddedAddon|null} */
export const embeddedAddon = null;
`;
async function resetEmbeddedAddon(): Promise<void> {
	await Bun.write(outputPath, stubContent);
	try {
		const entries = await fs.readdir(nativeDir);
		await Promise.all(
			entries
				.filter(entry => entry.startsWith(archivePrefix) && entry.endsWith(archiveSuffix))
				.map(entry => fs.unlink(path.join(nativeDir, entry))),
		);
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
	}
}

interface CandidateAddon {
	variant: "modern" | "baseline" | "default";
	filename: string;
}

interface AvailableAddon extends CandidateAddon {
	path: string;
	size: number;
}

/**
 * Validate and embed native addons for one standalone-binary target.
 */
export async function embedNativeAddon({
	targetPlatform,
	targetArch,
	nativeDir,
	outputPath,
	version,
}: {
	targetPlatform: string;
	targetArch: string;
	nativeDir: string;
	outputPath: string;
	version: string;
}): Promise<void> {
	const platformTag = `${targetPlatform}-${targetArch}`;
	const candidates: CandidateAddon[] =
		targetArch === "x64"
			? [
					{ variant: "modern", filename: `pi_natives.${platformTag}-modern.node` },
					{ variant: "baseline", filename: `pi_natives.${platformTag}-baseline.node` },
				]
			: [{ variant: "default", filename: `pi_natives.${platformTag}.node` }];

	const available: AvailableAddon[] = [];
	for (const candidate of candidates) {
		const candidatePath = path.join(nativeDir, candidate.filename);
		try {
			const stat = await fs.stat(candidatePath);
			available.push({ ...candidate, path: candidatePath, size: stat.size });
		} catch (err) {
			if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
		}
	}

	if (available.length === 0) {
		const expected = candidates.map(candidate => `  - ${candidate.filename}`).join("\n");
		throw new Error(`No native addons found for ${platformTag}. Expected one of:\n${expected}`);
	}

	const archiveFilename = `${archivePrefix}${platformTag}${archiveSuffix}`;
	const archivePath = path.join(nativeDir, archiveFilename);
	const archiveEntries: Record<string, Uint8Array> = {};
	const versionSentinel = versionSentinelFor(version);
	for (const addon of available) {
		const bytes = await fs.readFile(addon.path);
		if (!containsVersionSentinel(bytes, versionSentinel)) {
			throw new Error(
				`Native addon ${addon.path} does not contain the @oh-my-pi/pi-natives@${version} version sentinel ` +
					`\`${versionSentinel}\`. Rebuild it or fetch @oh-my-pi/pi-natives-${platformTag}@${version} before embedding.`,
			);
		}
		archiveEntries[addon.filename] = bytes;
	}
	await Bun.write(archivePath, await buildAddonArchive(archiveEntries));

	const files = available
		.map(
			addon =>
				`\t\t{ variant: ${JSON.stringify(addon.variant)}, filename: ${JSON.stringify(addon.filename)}, size: ${addon.size} },`,
		)
		.join("\n");

	const content = `
// AUTOGENERATED FILE -- DO NOT EDIT DIRECTLY
// See scripts/embed-native.ts

${embeddedAddonTypedefs}

import archivePath from ${JSON.stringify(`../native/${archiveFilename}`)} with { type: "file" };

export const embeddedAddon = {
\tplatformTag: ${JSON.stringify(platformTag)},
\tversion: ${JSON.stringify(version)},
\tarchive: {
\t\tformat: "tar.gz",
\t\tfilename: ${JSON.stringify(archiveFilename)},
\t\tfilePath: archivePath,
\t},
\tfiles: [
${files}
\t],
};
`;

	await Bun.write(outputPath, content);
}

async function main(): Promise<void> {
	if (process.argv.includes("--reset")) {
		await resetEmbeddedAddon();
		return;
	}

	const packageJson = (await Bun.file(packageJsonPath).json()) as { version: string };
	await embedNativeAddon({
		targetPlatform: Bun.env.TARGET_PLATFORM || process.platform,
		targetArch: Bun.env.TARGET_ARCH || process.arch,
		nativeDir,
		outputPath,
		version: packageJson.version,
	});
}

if (import.meta.main) {
	await main();
}
